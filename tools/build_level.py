#!/usr/bin/env python3
"""Deterministic route compiler: shared Lua collision data and closed soil/rim meshes."""
import json, math, sys
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
def write(path,text):
 if '--check' in sys.argv:
  if not path.exists() or path.read_text()!=text:raise SystemExit(f'Stale generated route: {path.relative_to(ROOT)}')
 else:path.write_text(text)
# Smoothstep interpolation gives zero slope at every crest, valley and charging platform.
knots=[[-500,220],[500,220],[740,255],[1050,350],[1190,260],[1460,220],
 [1750,240],[2050,230],[3150,230],[3450,175],[3750,175],
 [4050,240],[4400,290],[4800,230],[5050,230],[6050,230],
 [6370,175],[6660,175],[7060,270],[7450,310],[7850,230],
 [8150,230],[9150,230],[9450,175],[9750,175],[10100,280],
 [10500,230],[11500,230],[11800,300],[12200,230],[12800,230]]
points=[]
for a,b in zip(knots,knots[1:]):
 n=max(math.ceil((b[0]-a[0])/16),math.ceil(6*abs(b[1]-a[1])/((b[0]-a[0])*.12)))
 for i in range(n):
  t=i/n;points.append([round(a[0]+(b[0]-a[0])*t,4),round(a[1]+(b[1]-a[1])*(t*t*(3-2*t)),4)])
points.append(knots[-1])
stations=[2650,5550,8650,11000]
stars=[]
for i,x in enumerate(range(650,12200,300)):
 for a,b in zip(points,points[1:]):
  if a[0]<=x<=b[0]:
   y=a[1]+(b[1]-a[1])*(x-a[0])/(b[0]-a[0]);break
 stars.append([x,round(y+80+(20 if i%4==2 else 0),4)])
data={'finish':12400,'knots':knots,'points':points,'stations':stations,'stars':stars}
write(ROOT/'assets/level.json',json.dumps(data,indent=2)+'\n')
def lua(v):
 if isinstance(v,list):return '{'+','.join(lua(x) for x in v)+'}'
 return str(v)
write(ROOT/'modules/level_data.lua','-- Generated by tools/build_level.py; do not edit.\nreturn {finish=12400,points='+lua(points)+',stations='+lua(stations)+',stars='+lua(stars)+'}\n')
for name,rim in [('terrain',False),('terrain-rim',True)]:
 pos=[];uv=[]
 for a,b in zip(points,points[1:]):
  bottom_a=a[1]-3 if rim else -2000;bottom_b=b[1]-3 if rim else -2000
  for x,y in [a,(a[0],bottom_a),b,b,(a[0],bottom_a),(b[0],bottom_b)]:
   pos.extend([x,y,-.1 if rim else -.2]);uv.extend([.5,.5] if rim else [x/128,y/128])
 write(ROOT/f'assets/{name}.buffer',json.dumps([{'name':'position','type':'float32','count':3,'data':pos},{'name':'texcoord0','type':'float32','count':2,'data':uv}],separators=(',',':'))+'\n')
print(f'{len(points)-1} segments; {(12400-180)//10} m; {len(stars)} stars; {len(stations)} stations')
